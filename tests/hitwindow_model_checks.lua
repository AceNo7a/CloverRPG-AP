local n=0
local function check(value,name) assert(value,name); n=n+1; print("PASS "..name) end
local f=assert(io.open(arg[1] or "external-tools/clover-diagnostics/clover_auto_parry.lua")); local source=f:read("*a"); f:close()
local core=assert(source:match("%-%- BEGIN TESTABLE LEARNING(.-)%-%- END TESTABLE LEARNING"))
local classify,newModel=assert(loadstring(core.."\nreturn classifyAnimationPaths,newHitWindowModel"))()
check(classify({"Server/Spear1"}),"combat server animation allowed")
check(classify({"Skills/RushingTempest"}),"attack name not mistaken for run locomotion")
check(not classify({"Movement/ClimbUp"}),"movement excluded")
check(not classify({"Executions/Blade/SpearExecuting"}),"executions excluded")
check(not classify({"Hit/Parried"}),"reactions excluded")
check(not classify({"Server/SwordIdle"}),"idle suffix excluded")
check(not classify({"Server/IdleSword"}),"idle name prefix excluded")
check(not classify({"Skills/Swing", "Executions/Shared"}),"excluded alias overrides combat alias")
check(not classify({"Unrecognized/Attack"}),"unclassified paths not automatically approved")
check(classify({"NPCS/DireWolf/Clawed Attack"}),"audited NPC combat folder eligible")
check(not classify({"NPCS/AlkeBoss/Walk"}),"NPC movement names excluded within combat root")
check(not classify({"NPCS/AlkeBoss/Jump"}),"NPC jump movement excluded")
check(not classify({"Magic/Dagon/Void Slash Victim"}),"victim animations excluded")
check(classify({"Crit/HeavyTrident"}) and classify({"Aerials/Sword"}) and classify({"Uppercuts/Uppercut"}),"audited weapon attack categories eligible")
check(classify({"Magic/Beast/HowlingSlash_1"}),"audited magic attack candidate eligible")
check(not classify({"NPCS/AlkeBoss/Staggered"}),"NPC stagger reaction excluded")
local model=newModel()
check(model:sample("1",.4)=="collecting" and not model:position("1"),"one observation cannot enable timing")
check(model:sample("1",.41)=="ready" and model:position("1")==.4,"two consistent observations enable median timing")
check(model:sample("1",.6)=="variable timing" and not model:position("1"),"outlier disables a ready timing")
for i=1,5 do model:sample("1",.6) end
check(model:position("1")==.6 and #model.rows["1"].samples==5,"bounded history recovers only after conflicting samples age out")
model:sample("1",.7,true)
check(not model:position("1") and model.rows["1"].blocked,"multiple hit windows invalidate timing")
model:sample("1",.6); model:sample("1",.6)
check(not model:position("1"),"multi-hit profile remains blocked until explicitly cleared")
local bad=newModel()
check(bad:sample("x",0/0)=="invalid position" and not bad:position("x"),"NaN cannot become a ready timing")
check(bad:sample("x",math.huge)=="invalid position","unbounded position rejected")
for i=1,256 do bad:sample(tostring(i),.4) end
check(bad:sample("extra",.4)=="profile limit","profile cache bounded")
print("PASS: "..n.." HitWindow model assertions.")
