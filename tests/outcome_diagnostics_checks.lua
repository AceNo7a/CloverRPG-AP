local f=assert(io.open(arg[1] or "clover_auto_parry.lua")); local source=f:read("*a"); f:close()
local core=assert(source:match("%-%- BEGIN OUTCOME DIAGNOSTICS(.-)%-%- END OUTCOME DIAGNOSTICS"))
local factory=assert(loadstring(core.."\nreturn newOutcomeDiagnostics"))()
local now,count,snapshots=0,0,0
local function check(ok,label) assert(ok,label); count=count+1; print("PASS "..label) end
local d=factory({now=function() return now end,snapshot=function(item,owner)
    snapshots=snapshots+1; return "health=100 mode="..(owner and owner.mode or "off")
end})
d:movement("START","fly",{mode="fly"});d:tick("fly",{mode="fly"})
check(#d.flight==1 and #d.lifecycle==1,"flight starts separate trace and critical record")
now=.1;d:tick("fly",{mode="fly"});check(#d.flight==1,"flight sampling is rate limited")
now=.3;d:tick("fly",{mode="fly"});check(#d.flight==2,"flight sampling resumes at interval")
d:movement("STOP","character reference changed",{mode="fly"})
now=.4;d:tick("off");check(#d.flight==2,"trace survives movement stop")
for i=1,500 do d:note("parry","noise") end
check(#d.lifecycle==2 and #d.flight==2,"parry noise cannot erase flight lifecycle or samples")
check(#d.parry==300 and d.dropped.parry==200,"bounded parry ring counts overwritten lines")
local before=snapshots;local row=d:attempt({id="123"},"mock")
check(snapshots==before,"attempt registration avoids heavyweight reads before F down")
d:inputResult(row,true);check(row.sent==true and d.parry[#d.parry]:find("accepted_by_game=unknown",1,true),"API success is not called parry success")
now=.52;d:released(row,true,"scheduled hold complete")
check(row.up==.52 and d.parry[#d.parry]:find("elapsed_ms=120.00",1,true),"release tracks actual hold duration")
now=.55;d:correlate("DAMAGE","amount=15")
check(d.parry[#d.parry]:find("after_up_ms=30.00",1,true) and d.parry[#d.parry]:find("association=temporal_only",1,true),"damage includes release interval and qualified association")
d:correlate("SELF_ANIMATION","id=456")
check(d.parry[#d.parry]:find("attempt=1",1,true),"self reaction is linked to recent input")
d:tick("off");check(d.parry[#d.parry]:find("POST_INPUT",1,true),"delayed snapshot records actual age")
local failed=d:attempt({id="789"},"mock");d:inputResult(failed,false,"failed");d:released(failed,false,"retry")
check(not failed.sent and failed.up==nil,"failed release does not fabricate release time")
now=3;d:correlate("DAMAGE","amount=5")
check(d.parry[#d.parry]:find("recent_attempt=none",1,true),"stale inputs are not correlated with new damage")
for i=1,100 do d:attempt({id=tostring(i)},"mock") end
check(#d.rows==32,"retained track references are bounded")
d:movement("START","fly",{mode="fly"})
check(#d.flight==0 and #d.lifecycle==3,"new flight replaces sample trace but preserves prior stop records")
local broken=factory({now=function() return now end,snapshot=function() error("missing instance") end})
check(broken:snapshot():find("snapshot_unavailable",1,true),"snapshot failures stay diagnostic")
check(d:export():find("overwritten=",1,true) and d:export():find("no authoritative",1,true),"export discloses bounds and evidence limits")
print("Outcome diagnostic assertions passed: "..count)
