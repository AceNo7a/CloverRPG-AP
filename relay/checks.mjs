import assert from 'node:assert/strict';
import worker,{validate} from './worker.mjs';
let n=0;
const check=(value,name)=>{assert.ok(value,name); n++;};
const body={schema:1,version:5,place:8248288152,placeVersion:68598,
  profiles:[{id:'12345',marker:.4,spread:.01,samples:3}]};
const env={DISCORD_WEBHOOK:'https://discord.com/api/webhooks/123/test-token',REPORT_LIMITER:{limit:async()=>({success:true})}};
let outbound, calls=0;
globalThis.fetch=async(url,options)=>{calls++; outbound=JSON.parse(options.body); return new Response('{}',{status:200});};
const req=(data=body)=>new Request('https://relay.example/report',{method:'POST',body:JSON.stringify(data)});
check(validate(body).profiles.length===1,'accept candidate schema');
check(validate({...body,version:6}).version===6,'accept v6 automatic reporter');
check(!validate({...body,version:7}),'reject unsupported client schema version');
check(!validate({...body,place:1}),'reject wrong place');
check(!validate({...body,profiles:[{...body.profiles[0],marker:NaN}]}),'reject non-finite marker');
check(!validate({...body,profiles:[{...body.profiles[0],spread:.1}]}),'reject inconsistent profile');
check(!validate({...body,profiles:[{...body.profiles[0],samples:1}]}),'reject collecting profile');
check(!validate({...body,profiles:Array(7).fill(body.profiles[0])}),'bound batch');
check((await worker.fetch(req({...body,username:'private',logs:'private',evidence:'@everyone'}),env)).status===204,'relay confirms delivery');
check(!JSON.stringify(outbound).includes('private') && !outbound.content.includes('@everyone'),'strip arbitrary client text');
check(outbound.allowed_mentions.parse.length===0,'disable mentions');
check((await worker.fetch(new Request('https://relay.example/report',{method:'POST',body:'x'.repeat(4097)}),env)).status===413,'bound body while reading');
check((await worker.fetch(new Request('https://relay.example/report',{method:'POST',body:'bad JSON'}),env)).status===400,'reject malformed JSON');
check((await worker.fetch(req(),{})).status===503,'fail closed without private configuration');
check((await worker.fetch(req(),{...env,REPORT_LIMITER:{limit:async()=>({success:false})}})).status===429,'honor relay quota');
globalThis.fetch=async()=>new Response(JSON.stringify({retry_after:180}),{status:429});
const limited=await worker.fetch(req(),env);
check(limited.status===429 && (await limited.json()).retry_after===180,'pass upstream retry delay without secret response body');
globalThis.fetch=async()=>{throw Error('secret URL must not appear');};
const failed=await worker.fetch(req(),env);
check(failed.status===503 && !(await failed.text()).includes('secret URL'),'sanitize transport exceptions');
console.log(`PASS: ${n} relay assertions; no real network requests.`);
